package com.mobileagent.core.agent

import com.mobileagent.core.data.TaskRepository
import com.mobileagent.core.llm.LlmClient
import com.mobileagent.core.llm.ResolvedModel
import com.mobileagent.core.model.AgentEventType
import com.mobileagent.core.model.ChatRequest
import com.mobileagent.core.model.JsonCodec
import com.mobileagent.core.model.LlmMessage
import com.mobileagent.core.model.PlanStep
import com.mobileagent.core.model.TaskPlan
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonPrimitive
import java.util.UUID

/**
 * Produces a persisted, resumable plan for multi-step goals. Planning is deliberately skipped for
 * short single-action requests, and a planning failure degrades to direct execution instead of
 * blocking the task.
 */
class Planner(
    private val llm: LlmClient,
    private val tasks: TaskRepository,
) {

    fun shouldPlan(goal: String): Boolean {
        val normalized = goal.lowercase()
        if (goal.length > 90) return true
        val multiStep = listOf(" then ", "然后", "之后", "并且", "同时", "分别", "每天", "定时", "并且", "and then", "step by step", "多个")
        return multiStep.any { normalized.contains(it) }
    }

    suspend fun createPlan(taskId: String, goal: String, model: ResolvedModel): TaskPlan? {
        val prompt = buildString {
            append("Break the user goal into 2-6 concrete steps. Reply with JSON only, no markdown:\n")
            append("{\"steps\":[{\"title\":\"short action\",\"tool\":\"tool.name or null\",\"detail\":\"what exactly to do\"}]}\n")
            append("Goal: ").append(goal)
        }
        val response = runCatching {
            llm.chat(
                config = model.provider,
                apiKey = model.apiKey,
                request = ChatRequest(
                    messages = listOf(
                        LlmMessage.system("You are a careful Android automation planner. Tools are real; never invent tool names."),
                        LlmMessage.user(prompt),
                    ),
                    temperature = 0.0,
                    maxTokens = 700,
                    stream = false,
                ),
            )
        }.getOrNull() ?: return null

        val json = extractJsonObject(response.content) ?: return null
        val stepsElement = json["steps"] ?: return null
        val steps = runCatching {
            stepsElement.jsonArray.mapIndexedNotNull { index, element ->
                val obj = runCatching { element as JsonObject }.getOrNull() ?: return@mapIndexedNotNull null
                val title = obj["title"]?.jsonPrimitive?.content?.trim().orEmpty()
                if (title.isBlank()) return@mapIndexedNotNull null
                PlanStep(
                    id = "step-${index + 1}-${UUID.randomUUID().toString().take(4)}",
                    title = title.take(140),
                    detail = obj["detail"]?.jsonPrimitive?.content?.take(400).orEmpty(),
                    toolHint = obj["tool"]?.jsonPrimitive?.content?.takeIf { it.isNotBlank() && it != "null" },
                )
            }
        }.getOrNull().orEmpty()

        if (steps.isEmpty()) return null

        val plan = TaskPlan(
            goal = goal,
            steps = steps.take(8),
            createdAt = System.currentTimeMillis(),
            notes = "Generated by ${model.label}",
        )
        tasks.updatePlan(taskId, plan)
        tasks.addEvent(
            taskId,
            null,
            AgentEventType.PLAN_CREATED,
            "Plan created with ${plan.steps.size} step(s)",
            JsonObject(mapOf("steps" to kotlinx.serialization.json.JsonPrimitive(plan.steps.joinToString(" | ") { it.title }))),
        )
        return plan
    }

    private fun extractJsonObject(text: String): JsonObject? {
        val start = text.indexOf('{')
        val end = text.lastIndexOf('}')
        if (start < 0 || end <= start) return null
        val candidate = text.substring(start, end + 1)
        return runCatching { JsonCodec.json.parseToJsonElement(candidate) as JsonObject }.getOrNull()
    }
}
